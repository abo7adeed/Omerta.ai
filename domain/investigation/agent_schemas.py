"""Uniform Pydantic contracts for Omerta.ai Specialist Investigation Agents.

Every investigative agent returns a standardized, typed result with:
- Numeric risk score (0-100 scale)
- Metric breakdowns
- Evidence identifiers
- Execution timings (ms)
- Data quality indicators
"""

from datetime import UTC, datetime
from enum import StrEnum
from typing import Any
from pydantic import BaseModel, Field


class AgentExecutionStatus(StrEnum):
    """Execution status for specialist investigation agents."""

    PENDING = "PENDING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    TIMED_OUT = "TIMED_OUT"
    SKIPPED = "SKIPPED"
    UNAVAILABLE = "UNAVAILABLE"
    NOT_APPLICABLE = "NOT_APPLICABLE"


class AgentFinding(BaseModel):
    """Specific finding or rule triggered by an investigative agent."""

    rule_id: str = Field(description="Unique rule or heuristic identifier")
    rule_name: str = Field(default="", description="Descriptive title of the finding")
    points: float = Field(default=0.0, description="Risk point contribution on 0-100 scale")
    severity: str = Field(default="MEDIUM", description="LOW | MEDIUM | HIGH | CRITICAL")
    reason: str = Field(description="Natural language explanation of why the rule fired")
    evidence_ids: list[str] = Field(default_factory=list, description="Associated evidence or telemetry keys")
    observed_values: dict[str, Any] = Field(default_factory=dict, description="Observed vs threshold values")


class AgentDataQuality(BaseModel):
    """Evaluation of the source data available to the agent."""

    history_available: bool = Field(default=True, description="Whether historical data existed")
    record_count: int = Field(default=0, description="Number of baseline records evaluated")
    lookback_days: int = Field(default=30, description="Observation lookback window in days")
    is_sufficient: bool = Field(default=True, description="Whether data quality met statistical threshold")
    quality_notes: str | None = Field(default=None, description="Caveats or limitations in data coverage")


class SpecialistAgentResult(BaseModel):
    """Universal Pydantic schema for all specialist investigative agents."""

    agent_name: str = Field(description="Unique display name of the specialist agent")
    agent_version: str = Field(default="1.0.0", description="Agent implementation version")
    status: AgentExecutionStatus = Field(default=AgentExecutionStatus.PENDING)
    score: float = Field(default=0.0, ge=0.0, le=100.0, description="Authoritative agent score on 0-100 scale")
    score_scale: str = Field(default="0-100", description="Scale format specification")
    raw_metrics: dict[str, Any] = Field(default_factory=dict, description="Numeric metrics and raw measurements")
    findings: list[AgentFinding] = Field(default_factory=list, description="Actionable findings generated by this agent")
    points_breakdown: dict[str, float] = Field(default_factory=dict, description="Itemized point contributions")
    evidence_ids: list[str] = Field(default_factory=list, description="Referenced evidence hashes and record identifiers")
    data_quality: AgentDataQuality = Field(default_factory=AgentDataQuality, description="Data availability and completeness assessment")
    started_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    completed_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    duration_ms: float = Field(default=0.0, description="Monotonic execution time in milliseconds")
    error_code: str | None = Field(default=None, description="Error code if agent failed or timed out")
    error_message: str | None = Field(default=None, description="Diagnostic error details")


