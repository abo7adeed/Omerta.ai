class TransactionHistoryMetrics(BaseModel):
    """Comprehensive numeric metrics computed across rolling historical windows."""

    # 5-minute window
    previous_transactions_5m: int = 0
    outgoing_total_5m: float = 0.0

    # 15-minute window
    previous_transactions_15m: int = 0
    outgoing_total_15m: float = 0.0

    # 60-minute window
    previous_transactions_60m: int = 0
    outgoing_total_60m: float = 0.0

    # 24-hour window
    previous_transactions_24h: int = 0
    outgoing_total_24h: float = 0.0

    # 7-day window
    previous_transactions_7d: int = 0
    outgoing_total_7d: float = 0.0

    # 30-day window
    previous_transactions_30d: int = 0
    outgoing_total_30d: float = 0.0
    incoming_total_30d: float = 0.0

    # Statistical baseline
    historical_average_amount: float = 0.0
    historical_median_amount: float = 0.0
    historical_max_amount: float = 0.0
    historical_p95_amount: float = 0.0

    # Current comparison
    current_amount: float = 0.0
    amount_to_average_ratio: float = 1.0
    amount_to_p95_ratio: float = 1.0

    # Counterparties and behavior
    withdrawal_count: int = 0
    withdrawal_total: float = 0.0
    distinct_beneficiaries_count: int = 0
    is_first_transaction_with_beneficiary: bool = False
    failed_reversed_count: int = 0
    time_since_last_transaction_seconds: float | None = None
    account_age_days: int = 0
    available_balance: float = 0.0


class VPNDetectionDetails(BaseModel):
    """Network and VPN intelligence telemetry."""

    vpn_detected: bool = False
    proxy_detected: bool = False
    detection_provider: str = "MaxMind / Omerta Network Intelligence"
    ip_risk_score: float = 0.0
    country_detected: str | None = None
    city_detected: str | None = None
    vpn_confidence: float = 0.0
    detection_status: str = "NOT_DETECTED"  # DETECTED | NOT_DETECTED | UNKNOWN | UNAVAILABLE
    evidence_ids: list[str] = Field(default_factory=list)


class ATOStep(BaseModel):
    """Observed event in an Account Takeover attack chain."""

    event_type: str
    timestamp: datetime
    time_delta_seconds: float
    description: str
    evidence_id: str
